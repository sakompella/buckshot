//! Writes the enum of Bend branch ids, `rules/src/branch/ids.rs`.

use std::fmt::Write as _;

use crate::bend::{Rules, Site};

pub fn ids(rules: &Rules, sites: &[&Site]) -> String {
    let mut out = String::new();
    let modules: Vec<String> = rules.modules.iter().map(|m| format!("{}.bend", m.name)).collect();
    let _ = writeln!(out, "// @generated by `cargo run -p branch-map -- write`. Do not edit.");
    let _ = writeln!(out, "// Bend sources: {}", modules.join(" "));
    let _ = writeln!(out, "// sha256: {}", rules.hash);
    out.push_str(
        "\n/// The Bend branches the rules mirror: one variant per branch site of the\n\
         /// defs reachable from `simple/main`'s `start`, `request` and `answer`,\n\
         /// less the defs `branch-map.toml` exempts.\n",
    );
    out.push_str("#[allow(dead_code)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub(crate) enum B {\n");
    for site in sites {
        let _ = writeln!(out, "    /// `{}` ({}.bend:{})", site.label(), site.module, site.line);
        let _ = writeln!(out, "    {},", site.variant);
    }
    out.push_str("}\n\n#[cfg(feature = \"trace\")]\nimpl B {\n    /// The Bend branch, as `module:def:pattern`.\n");
    out.push_str("    pub(crate) const fn label(self) -> &'static str {\n        match self {\n");
    for site in sites {
        let _ = writeln!(out, "            Self::{} => {:?},", site.variant, site.label());
    }
    out.push_str("        }\n    }\n}\n");
    out
}
